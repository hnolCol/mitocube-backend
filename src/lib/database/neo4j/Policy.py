from typing import List, Optional

from neo4j import Driver, Result

from lib.database.abstract.Policy import PolicyABC
from config.models.Policy import (PolicyModel, PolicyInsertModel, PolicyUpdateModel,
                                  PolicyStatusModel, PolicyVersionModel, POLICY_TYPES)


class Neo4JPolicy(PolicyABC):

    def __init__(self, driver : Driver) -> None:
        self._driver = driver

    def list(self) -> List[PolicyModel]:
        "Returns the policies (terms of use, data protection) that exist, in the order of POLICY_TYPES."
        query = (
            "MATCH (p:Policy) WHERE p.type IN $types "
            "RETURN properties(p) "
        )
        r = self._driver.execute_query(query, routing_="r", types=POLICY_TYPES, result_transformer_=Result.value)
        return sorted([PolicyModel(**ri) for ri in r], key=lambda p: POLICY_TYPES.index(p.type))

    def get(self, tag : str) -> Optional[PolicyModel]:
        "Returns the policy with the given tag, or None if it does not exist."
        query = (
            "MATCH (p:Policy {tag : $tag}) "
            "RETURN properties(p) "
        )
        r = self._driver.execute_query(query, routing_="r", tag=tag, result_transformer_=Result.value)
        return PolicyModel(**r[0]) if len(r) > 0 else None

    def history(self, tag : str) -> List[PolicyVersionModel]:
        "Returns the archived (older) versions of the policy, newest first."
        query = (
            "MATCH (v:PolicyVersion {policy_tag : $tag}) "
            "RETURN properties(v) ORDER BY v.version DESC "
        )
        r = self._driver.execute_query(query, routing_="r", tag=tag, result_transformer_=Result.value)
        return [PolicyVersionModel(**ri) for ri in r]

    def create(self, policy : PolicyInsertModel, user_tag : str) -> PolicyModel:
        "Creates the policy of the given type. The tag is generated by PolicyInsertModel."
        exists_query = "MATCH (p:Policy {type : $type}) RETURN count(p) "
        n = self._driver.execute_query(exists_query, routing_="r", type=policy.type, result_transformer_=Result.value)
        if n[0] > 0:
            raise ValueError(f"The policy '{policy.type}' already exists. Edit it instead.")

        query = (
            "CREATE (p:Policy {tag : $tag, type : $type, title : $title, text : $text, required : $required, "
            "    version : 1, created_at : timestamp(), created_by : $user_tag, "
            "    updated_at : timestamp(), updated_by : $user_tag}) "
            "RETURN properties(p) "
        )
        r = self._driver.execute_query(query, routing_="w",
                                       tag=policy.tag,
                                       type=policy.type,
                                       title=policy.title,
                                       text=policy.text,
                                       required=policy.required,
                                       user_tag=user_tag,
                                       result_transformer_=Result.value)
        return PolicyModel(**r[0])

    def update(self, tag : str, policy : PolicyUpdateModel, user_tag : str) -> Optional[PolicyModel]:
        """Updates the policy. If bump_version is True, the current version is archived first,
        the version is increased and all users have to agree again."""
        query = (
            "MATCH (p:Policy {tag : $tag}) "
            "FOREACH (_ IN CASE WHEN $bump_version THEN [1] ELSE [] END | "
            "    CREATE (v:PolicyVersion {policy_tag : p.tag, version : p.version, title : p.title, "
            "        text : p.text, required : p.required, updated_at : p.updated_at, "
            "        updated_by : p.updated_by, archived_at : timestamp()}) "
            "    CREATE (p)-[:HAS_VERSION]->(v)) "
            "SET p.title = $title, p.text = $text, p.required = $required, "
            "    p.updated_at = timestamp(), p.updated_by = $user_tag, "
            "    p.version = CASE WHEN $bump_version THEN p.version + 1 ELSE p.version END "
            "RETURN properties(p) "
        )
        r = self._driver.execute_query(query, routing_="w",
                                       tag=tag,
                                       title=policy.title,
                                       text=policy.text,
                                       required=policy.required,
                                       bump_version=policy.bump_version,
                                       user_tag=user_tag,
                                       result_transformer_=Result.value)
        return PolicyModel(**r[0]) if len(r) > 0 else None

    def delete(self, tag : str) -> bool:
        "Deletes the policy together with its archived versions and all user agreements to it."
        query = (
            "MATCH (p:Policy {tag : $tag}) "
            "OPTIONAL MATCH (p)-[:HAS_VERSION]->(v:PolicyVersion) "
            "WITH p, p.tag AS deleted_tag, collect(v) AS versions "
            "DETACH DELETE p "
            "FOREACH (v IN versions | DETACH DELETE v) "
            "RETURN deleted_tag "
        )
        r = self._driver.execute_query(query, routing_="w", tag=tag, result_transformer_=Result.value)
        return len(r) > 0

    def agree(self, tag : str, user_tag : str) -> bool:
        "Marks the user as agreed to the current version of the policy."
        query = (
            "MATCH (p:Policy {tag : $tag}) "
            "MATCH (u:User {tag : $user_tag}) "
            "MERGE (u)-[a:AGREED_TO]->(p) "
            "SET a.version = p.version, a.at = timestamp() "
            "RETURN true "
        )
        r = self._driver.execute_query(query, routing_="w", tag=tag, user_tag=user_tag, result_transformer_=Result.value)
        return r[0] if len(r) > 0 else False

    def get_status(self, user_tag : str) -> List[PolicyStatusModel]:
        "Returns for every existing policy whether the user has to agree to it before using MitoCube."
        query = (
            "MATCH (u:User {tag : $user_tag}) "
            "MATCH (p:Policy) WHERE p.type IN $types "
            "OPTIONAL MATCH (u)-[a:AGREED_TO]->(p) "
            "RETURN p.tag AS tag, p.type AS type, p.title AS title, "
            "       coalesce(p.required, false) AS required, "
            "       coalesce(a.version = p.version, false) AS agreed, "
            "       coalesce(p.version, 1) AS version "
        )
        r = self._driver.execute_query(query, routing_="r", user_tag=user_tag, types=POLICY_TYPES, result_transformer_=Result.data)
        statuses = [PolicyStatusModel(**row, must_agree=row["required"] and not row["agreed"]) for row in r]
        return sorted(statuses, key=lambda s: POLICY_TYPES.index(s.type))